// Build: contrast check → QR symbol → print PDF + preview PNG for every palette, into dist/.
import { mkdir, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";
import { serve } from "./serve.mjs";
import { checkContrast } from "./check.mjs";

const SITE = "https://helixbiology.sch.ac";
const CHROME = process.env.CHROME || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const PORT = 4321;
const at = p => fileURLToPath(new URL(`../${p}`, import.meta.url));

const themes = checkContrast();

// QR as an SVG symbol coloured by --qr-fg; the card's white space is the quiet zone.
const { modules } = QRCode.create(SITE, { errorCorrectionLevel: "M" });
const n = modules.size;
let d = "";
for (let y = 0; y < n; y++)
  for (let x = 0; x < n; x++) {
    if (!modules.get(y, x)) continue;
    let w = 1;
    while (x + w < n && modules.get(y, x + w)) w++;
    d += `M${x} ${y}h${w}v1h-${w}z`;
    x += w - 1;
  }
await writeFile(at("brand/qr.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg">\n  <!-- Generated by scripts/build.mjs from ${SITE}. Do not edit. -->\n  <symbol id="qr" viewBox="0 0 ${n} ${n}"><path shape-rendering="crispEdges" style="fill:var(--qr-fg)" d="${d}"/></symbol>\n</svg>\n`);

await mkdir(at("dist"), { recursive: true });
const server = serve(PORT);
const chrome = (...args) =>
  promisify(execFile)(CHROME, ["--headless", "--disable-gpu", "--hide-scrollbars", "--virtual-time-budget=10000", ...args])
    .catch(e => { if (!/bytes written to file/.test(e.stderr)) throw e; }); // Chrome on macOS sometimes crashes on exit after writing the file
try {
  for (const t of themes) {
    const url = `http://localhost:${PORT}/card/?theme=${t}`;
    await chrome(`--print-to-pdf=${at(`dist/helix-card-${t}.pdf`)}`, "--no-pdf-header-footer", url);
    await chrome(`--screenshot=${at(`dist/helix-card-${t}.png`)}`, "--window-size=816,288", "--force-device-scale-factor=3", url);
    console.log("built", t);
  }
} finally {
  server.close();
}
